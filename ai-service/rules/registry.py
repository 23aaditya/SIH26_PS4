def get_applicable_rules(category_code: str, app_data: Dict[str, Any]) -> List[RuleDefinition]:
    """
    Select and return the authoritative list of applicable statutory rules
    for a given canonical application category code and application dossier.
    Combines applicable common operational checks with category-specific substantive checks.
    """
    if category_code not in CANONICAL_APPLICATION_TYPES and category_code != "unknown":
        category_code = "unknown"

    applicable: List[RuleDefinition] = []
    for rule in RULE_CATALOG.values():
        if rule.is_applicable(app_data, category_code):
            applicable.append(rule)

    return applicable
