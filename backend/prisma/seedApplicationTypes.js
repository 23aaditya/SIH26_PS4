export async function seedApplicationTypes() {
  console.log("Seeding AICTE Dynamic Application Types & Document Requirements...");

  for (const appType of APPLICATION_TYPES_CONFIG) {
    const createdType = await prisma.applicationType.upsert({
      where: { code: appType.code },
      update: {
        name: appType.name,
        category: appType.category,
        description: appType.description,
        displayOrder: appType.displayOrder,
        requiresEvc: appType.requiresEvc,
        active: true,
      },
      create: {
        code: appType.code,
        name: appType.name,
        category: appType.category,
        description: appType.description,
        displayOrder: appType.displayOrder,
        requiresEvc: appType.requiresEvc,
        active: true,
      },
    });

    // Seed Field Definitions
    for (const f of appType.fields) {
      const existingField = await prisma.applicationFieldDefinition.findFirst({
        where: {
          applicationTypeId: createdType.id,
          fieldKey: f.fieldKey,
        },
      });

      if (existingField) {
        await prisma.applicationFieldDefinition.update({
          where: { id: existingField.id },
          data: {
            label: f.label,
            fieldType: f.fieldType,
            placeholder: f.placeholder,
            required: f.required,
            optionsJson: f.optionsJson || null,
            validationRule: f.validationRule || null,
            displayOrder: f.displayOrder,
            section: f.section,
            active: true,
          },
        });
      } else {
        await prisma.applicationFieldDefinition.create({
          data: {
            applicationTypeId: createdType.id,
            fieldKey: f.fieldKey,
            label: f.label,
            fieldType: f.fieldType,
            placeholder: f.placeholder,
            required: f.required,
            optionsJson: f.optionsJson || null,
            validationRule: f.validationRule || null,
            displayOrder: f.displayOrder,
            section: f.section,
            active: true,
          },
        });
      }
    }

    // Seed Document Requirements
    for (const doc of appType.documents) {
      const existingDoc = await prisma.applicationDocumentRequirement.findFirst({
        where: {
          applicationTypeId: createdType.id,
          documentName: doc.documentName,
        },
      });

      if (existingDoc) {
        await prisma.applicationDocumentRequirement.update({
          where: { id: existingDoc.id },
          data: {
            description: doc.description,
            required: doc.required,
            allowedExtensions: doc.allowedExtensions,
            maxSizeMb: doc.maxSizeMb,
            displayOrder: doc.displayOrder,
          },
        });
      } else {
        await prisma.applicationDocumentRequirement.create({
          data: {
            applicationTypeId: createdType.id,
            documentName: doc.documentName,
            description: doc.description,
            required: doc.required,
            allowedExtensions: doc.allowedExtensions,
            maxSizeMb: doc.maxSizeMb,
            displayOrder: doc.displayOrder,
          },
        });
      }
    }
  }

  const countTypes = await prisma.applicationType.count();
  const countFields = await prisma.applicationFieldDefinition.count();
  const countDocs = await prisma.applicationDocumentRequirement.count();
  console.log(`Successfully seeded ${countTypes} Application Types with ${countFields} Fields and ${countDocs} Document Requirements.`);
}

if (process.argv[1]?.endsWith("seedApplicationTypes.js")) {
  seedApplicationTypes()
    .then(() => process.exit(0))
    .catch((err) => {
      console.error("Error seeding application types:", err);
      process.exit(1);
    });
}
